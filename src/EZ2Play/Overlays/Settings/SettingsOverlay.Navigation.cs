
using System;
using System.Windows;
using System.Windows.Controls;

namespace EZ2Play.App
{
    /// <summary>
    /// Handles navigation, selection highlighting,
    /// and exit confirmation within SettingsOverlay.
    /// </summary>
    /// <remarks>
    /// This partial class shares its state and UI elements
    /// with SettingsOverlay.xaml.cs.
    ///
    /// It contains only navigation-related behavior.
    /// Settings initialization, configuration changes,
    /// and overlay animations remain in the main file.
    /// </remarks>
    public partial class SettingsOverlay
    {
        /// <summary>
        /// Refreshes the settings selector when
        /// the overlay is visible and not closing.
        /// </summary>
        public void RefreshSelector()
        {
            if (Visibility == Visibility.Visible && !_isClosing)
                UpdateOverlaySelector();
        }

        /// <summary>
        /// Updates the selector target according to
        /// the currently active settings list.
        /// </summary>
        /// <remarks>
        /// The selector follows one of three areas:
        /// the main settings list, nested startup options,
        /// or the exit confirmation list.
        ///
        /// The active list determines which element
        /// and selector profile are passed to
        /// SelectorCoordinator.
        /// </remarks>
        private void UpdateOverlaySelector()
        {
            if (_selectorCoordinator == null)
                return;

            if (Visibility != Visibility.Visible || _isClosing)
            {
                _selectorCoordinator.Hide(
                    SelectorCoordinator.Owner.Settings);

                return;
            }

            ListBox activeListBox;

            // Exit confirmation has its own navigation list.
            if (_exitConfirmationMode)
            {
                var target =
                    ExitConfirmationListBox.SelectedItem as ListBoxItem;

                _selectorCoordinator.ShowOverlay(
                    SelectorCoordinator.Owner.Settings,
                    target,
                    _selectorCoordinator.CreateOverlayItemProfile(),
                    ExitConfirmationListBox);

                return;
            }
            // Use nested options when the autorun group is active.
            else if (SettingsListBox.SelectedItem == TreeItemsContainer &&
                     TreeItemsContainer.Visibility == Visibility.Visible)
            {
                activeListBox = SubOptionsListBox;
            }
            else
            {
                activeListBox = SettingsListBox;
            }

            // Hide the selector when nothing is selected.
            if (activeListBox.SelectedIndex < 0)
            {
                _selectorCoordinator.ShowOverlay(
                    SelectorCoordinator.Owner.Settings,
                    null,
                    null);

                return;
            }

            var selectedItem =
                activeListBox.ItemContainerGenerator.ContainerFromIndex(
                    activeListBox.SelectedIndex) as ListBoxItem;

            // The container may not yet be generated by WPF.
            if (selectedItem == null)
            {
                _selectorCoordinator.ShowOverlay(
                    SelectorCoordinator.Owner.Settings,
                    null,
                    null);

                return;
            }

            _selectorCoordinator.ShowOverlay(
                SelectorCoordinator.Owner.Settings,
                selectedItem,
                _selectorCoordinator.CreateOverlayItemProfile(),
                activeListBox);
        }

        /// <summary>
        /// Handles selection changes in the settings
        /// and exit confirmation lists.
        /// </summary>
        /// <remarks>
        /// Ignores routed events originating from
        /// a different element.
        /// </remarks>
        private void OnSelectionChanged(
            object sender,
            SelectionChangedEventArgs e)
        {
            if (!ReferenceEquals(e.OriginalSource, sender))
                return;

            UpdateSelectionState();
            UpdateOverlaySelector();
        }

        /// <summary>
        /// Maintains the selected nested startup option
        /// when entering or leaving the autorun group.
        /// </summary>
        /// <remarks>
        /// The selected nested index is remembered when
        /// navigating away from the group.
        ///
        /// When returning, the stored index is restored
        /// within the current item range.
        /// </remarks>
        private void UpdateSelectionState()
        {
            bool isSubOptionsActive =
                !_exitConfirmationMode &&
                SettingsListBox.SelectedItem == TreeItemsContainer &&
                TreeItemsContainer.Visibility == Visibility.Visible;

            if (isSubOptionsActive)
            {
                if (SubOptionsListBox.SelectedIndex == -1 &&
                    SubOptionsListBox.Items.Count > 0)
                {
                    int index = Math.Max(
                        0,
                        Math.Min(
                            _subOptionsSelectedIndex,
                            SubOptionsListBox.Items.Count - 1));

                    SubOptionsListBox.SelectedIndex = index;
                }

                return;
            }

            if (SubOptionsListBox.SelectedIndex >= 0)
            {
                _subOptionsSelectedIndex =
                    SubOptionsListBox.SelectedIndex;

                SubOptionsListBox.SelectedIndex = -1;
            }
        }

        /// <summary>
        /// Moves the selection through the settings interface.
        /// </summary>
        /// <param name="direction">
        /// Direction of navigation, normally -1 or 1.
        /// </param>
        /// <param name="isHorizontal">
        /// True for horizontal navigation; false for vertical.
        /// </param>
        /// <remarks>
        /// Horizontal navigation is used by nested startup
        /// options and the exit confirmation list.
        ///
        /// Vertical navigation moves between top-level settings.
        /// Items that are not visible are skipped.
        ///
        /// Successful selection changes play the
        /// application's movement sound.
        /// </remarks>
        public void Navigate(int direction, bool isHorizontal = true)
        {
            // Exit confirmation accepts horizontal navigation only.
            if (_exitConfirmationMode)
            {
                if (!isHorizontal)
                    return;

                int newIndex =
                    ExitConfirmationListBox.SelectedIndex + direction;

                if (newIndex >= 0 &&
                    newIndex < ExitConfirmationListBox.Items.Count)
                {
                    ExitConfirmationListBox.SelectedIndex = newIndex;

                    _mainWindow.GetSound()?.PlayMoveSound();
                }

                return;
            }

            // Horizontal navigation through nested startup options.
            if (isHorizontal)
            {
                if (SettingsListBox.SelectedItem == TreeItemsContainer &&
                    TreeItemsContainer.Visibility == Visibility.Visible)
                {
                    int newIndex =
                        SubOptionsListBox.SelectedIndex + direction;

                    while (newIndex >= 0 &&
                           newIndex < SubOptionsListBox.Items.Count)
                    {
                        var targetItem =
                            SubOptionsListBox.Items[newIndex] as ListBoxItem;

                        if (targetItem != null &&
                            targetItem.Visibility == Visibility.Visible)
                        {
                            SubOptionsListBox.SelectedIndex = newIndex;

                            _mainWindow.GetSound()?.PlayMoveSound();

                            return;
                        }

                        newIndex += direction;
                    }
                }

                return;
            }

            // Vertical navigation through top-level settings.
            int newIndexVert =
                SettingsListBox.SelectedIndex + direction;

            while (newIndexVert >= 0 &&
                   newIndexVert < SettingsListBox.Items.Count)
            {
                var item =
                    SettingsListBox.Items[newIndexVert] as ListBoxItem;

                if (item != null &&
                    item.Visibility == Visibility.Visible)
                {
                    SettingsListBox.SelectedIndex = newIndexVert;

                    SettingsListBox.ScrollIntoView(
                        SettingsListBox.SelectedItem);

                    _mainWindow.GetSound()?.PlayMoveSound();

                    // Restore nested selection when entering
                    // the startup options group.
                    if (item == TreeItemsContainer)
                    {
                        if (SubOptionsListBox.SelectedIndex == -1)
                        {
                            for (int i = 0;
                                 i < SubOptionsListBox.Items.Count;
                                 i++)
                            {
                                if ((SubOptionsListBox.Items[i] as ListBoxItem)
                                    ?.Visibility == Visibility.Visible)
                                {
                                    SubOptionsListBox.SelectedIndex = i;
                                    break;
                                }
                            }
                        }
                    }

                    return;
                }

                newIndexVert += direction;
            }
        }

        /// <summary>
        /// Displays the exit confirmation interface
        /// when the application is using an external display.
        /// </summary>
        /// <remarks>
        /// Hides the normal settings list and activates
        /// the confirmation selection list.
        ///
        /// The selector is updated after the
        /// confirmation mode becomes active.
        /// </remarks>
        private void ShowExitDisplayConfirmation()
        {
            _exitConfirmationMode = true;

            SettingsListBox.Visibility = Visibility.Collapsed;

            ExitConfirmText.Visibility = Visibility.Visible;
            ExitConfirmationListBox.Visibility = Visibility.Visible;
            ExitConfirmationListBox.SelectedIndex = 0;

            ExitConfirmationListBox.Focus();

            UpdateSelectionState();
            UpdateOverlaySelector();
        }

        /// <summary>
        /// Hides exit confirmation and restores
        /// the normal settings interface.
        /// </summary>
        /// <param name="focusSettings">
        /// Whether to restore keyboard focus
        /// to the settings list when visible.
        /// </param>
        private void HideExitDisplayConfirmation(
            bool focusSettings = true)
        {
            _exitConfirmationMode = false;

            ExitConfirmText.Visibility = Visibility.Collapsed;
            ExitConfirmationListBox.Visibility = Visibility.Collapsed;

            SettingsListBox.Visibility = Visibility.Visible;

            if (focusSettings && Visibility == Visibility.Visible)
                SettingsListBox.Focus();

            UpdateSelectionState();
            UpdateOverlaySelector();
        }
    }
}
